// Este motor toma tu formato de objetos y lo inyecta en la plataforma
ejerciciosB1.forEach((ejercicio, index) => {
    
    // Nivel B1 abarca los ejercicios 401 al 600 globales
    const idGlobal = 401 + index; 
    
    // Calcula a qué unidad pertenece (Unidades 81 a 120, a 5 ejercicios por unidad)
    const unitId = Math.ceil(idGlobal / 5); 

    // Crea la unidad visualmente si no existe
    if (!UNITS_META.find(u => u.id === unitId)) {
        UNITS_META.push({
            id: unitId,
            level: "B1",
            title: `Unidad ${unitId}: ${ejercicio.type || 'Práctica Intermedia'}`,
            desc: "Evaluación y consolidación de estructuras lingüísticas."
        });
    }

    // Formatea las opciones (A, B, C, D) para la interfaz
    const letras = ['a', 'b', 'c', 'd'];
    const formattedOptions = ejercicio.options.map((optText, i) => {
        return {
            id: letras[i],
            text: optText,
            isCorrect: i === ejercicio.correct
        };
    });

    // Inserta en la base de datos maestra
    EXERCISES_DATA.push({
        globalId: idGlobal,
        unitId: unitId,
        question: ejercicio.question,
        options: formattedOptions,
        feedbackCorrect: ejercicio.feedback[ejercicio.correct].replace('✅ ', ''),
        feedbackWrong: `La respuesta correcta era la ${letras[ejercicio.correct].toUpperCase()}. ${ejercicio.feedback[ejercicio.correct].replace('✅ Correcto. ', '')}`
    });
});